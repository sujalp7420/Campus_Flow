-- CampusFlow Supabase database setup
-- Run this entire file once in Supabase Dashboard > SQL Editor.
-- User passwords are created and managed in Supabase Authentication.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.offices (
  id bigint generated by default as identity primary key,
  name text not null unique,
  room text,
  phone text,
  email text,
  working_hours text,
  lunch_break text,
  created_at timestamptz not null default now()
);

create table if not exists public.procedures (
  id bigint generated by default as identity primary key,
  title text not null,
  category_id text,
  category_name text not null default '',
  office_id bigint references public.offices(id) on delete set null,
  office text not null default '',
  working_hours text not null default '9:00 AM - 4:00 PM',
  description text not null default '',
  processing_time text not null default '1-2 Days',
  fee numeric(12, 2) not null default 0 check (fee >= 0),
  required_documents jsonb not null default '[]'::jsonb,
  steps jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.procedure_steps (
  id bigint generated by default as identity primary key,
  procedure_id bigint not null references public.procedures(id) on delete cascade,
  step_number integer not null check (step_number > 0),
  title text not null,
  description text,
  created_at timestamptz not null default now(),
  unique (procedure_id, step_number)
);

create table if not exists public.progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  procedure_id text not null,
  completed_steps jsonb not null default '[]'::jsonb,
  total_steps integer not null default 0,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, procedure_id)
);

create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  procedure_id text not null,
  created_at timestamptz not null default now(),
  unique (user_id, procedure_id)
);

create index if not exists procedures_category_id_idx on public.procedures(category_id);
create index if not exists procedures_office_id_idx on public.procedures(office_id);
create index if not exists progress_user_id_idx on public.progress(user_id);
create index if not exists favorites_user_id_idx on public.favorites(user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.email, '')
  )
  on conflict (id) do update
  set name = excluded.name, email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Backfill profiles for accounts created before this script was run.
insert into public.profiles (id, name, email)
select
  id,
  coalesce(raw_user_meta_data ->> 'name', ''),
  coalesce(email, '')
from auth.users
on conflict (id) do nothing;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists procedures_set_updated_at on public.procedures;
create trigger procedures_set_updated_at
before update on public.procedures
for each row execute procedure public.set_updated_at();

drop trigger if exists progress_set_updated_at on public.progress;
create trigger progress_set_updated_at
before update on public.progress
for each row execute procedure public.set_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

grant usage, select on all sequences in schema public to authenticated;

grant select on public.profiles, public.categories, public.offices,
  public.procedures, public.procedure_steps, public.progress, public.favorites to authenticated;
grant insert, update, delete on public.categories, public.offices,
  public.procedures, public.procedure_steps to authenticated;
grant insert, update, delete on public.progress to authenticated;
grant insert, update, delete on public.favorites to authenticated;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.offices enable row level security;
alter table public.procedures enable row level security;
alter table public.procedure_steps enable row level security;
alter table public.progress enable row level security;
alter table public.favorites enable row level security;

drop policy if exists profiles_select_own_or_admin on public.profiles;
create policy profiles_select_own_or_admin on public.profiles
for select to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists catalog_read on public.categories;
create policy catalog_read on public.categories
for select to authenticated using (true);

drop policy if exists catalog_admin_write on public.categories;
create policy catalog_admin_write on public.categories
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists offices_read on public.offices;
create policy offices_read on public.offices
for select to authenticated using (true);

drop policy if exists offices_admin_write on public.offices;
create policy offices_admin_write on public.offices
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists procedures_read on public.procedures;
create policy procedures_read on public.procedures
for select to authenticated using (true);

drop policy if exists procedures_admin_write on public.procedures;
create policy procedures_admin_write on public.procedures
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists procedure_steps_read on public.procedure_steps;
create policy procedure_steps_read on public.procedure_steps
for select to authenticated using (true);

drop policy if exists procedure_steps_admin_write on public.procedure_steps;
create policy procedure_steps_admin_write on public.procedure_steps
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists progress_own_rows on public.progress;
create policy progress_own_rows on public.progress
for all to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

drop policy if exists favorites_own_rows on public.favorites;
create policy favorites_own_rows on public.favorites
for all to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

